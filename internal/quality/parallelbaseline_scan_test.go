func TestScanSerialTestsReportsAParseErrorAsAWalkFailure(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	writeScanFixture(t, root, "pkg", "broken_test.go", "package pkg\n\nfunc TestBroken(t *testing.T {\n")

	_, _, err := ScanSerialTests(root)
	if err == nil {
		t.Fatal("ScanSerialTests accepted a file with a syntax error")
	}
	if !strings.Contains(err.Error(), "walk") || !strings.Contains(err.Error(), "parse") {
		t.Fatalf("error %q does not name both the walk and the parse failure", err)
	}
}

func TestScanSerialTestsSkipsFunctionsWithTheWrongSignature(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	writeScanFixture(t, root, "pkg", "wrong_signature_test.go", `package pkg

import "testing"

func TestMain(m *testing.M) {}

func NotATestFunction() {}

func TestWrongParamCount(t *testing.T, extra int) {}

func TestRight(t *testing.T) {
	t.Parallel()
}
`)

	serial, bareNolint, err := ScanSerialTests(root)
	if err != nil {
		t.Fatalf("ScanSerialTests: %v", err)
	}
	if len(bareNolint) != 0 {
		t.Fatalf("bareNolint = %v, want none", bareNolint)
	}
	for _, entry := range serial {
		if entry.Key == "pkg::TestMain" || entry.Key == "pkg::TestWrongParamCount" || entry.Key == "pkg::TestRight" {
			t.Fatalf("ScanSerialTests reported %q, want it skipped or parallel", entry.Key)
		}
	}
}

