// TestParallelGuardModuleRootReturnsErrorWhenCallerCannotBeResolved pins
// ParallelGuardModuleRoot's defensive branch for runtime.Caller failing --
// unreachable from a real, fixed skip=1 call, so it is exercised through
// the callerLookup seam instead.
//
//nolint:paralleltest // mutates the package-level callerLookup seam
func TestParallelGuardModuleRootReturnsErrorWhenCallerCannotBeResolved(t *testing.T) {
	original := callerLookup
	t.Cleanup(func() { callerLookup = original })
	callerLookup = func(int) (uintptr, string, int, bool) { return 0, "", 0, false }

	if _, err := ParallelGuardModuleRoot(); err == nil {
		t.Fatal("ParallelGuardModuleRoot returned no error when the caller could not be resolved")
	}
}

// TestParallelGuardModuleRootReturnsErrorWhenNoGoModExists pins the other
// walk-up failure: no go.mod anywhere above the caller's directory.
//
//nolint:paralleltest // mutates the package-level callerLookup seam
func TestParallelGuardModuleRootReturnsErrorWhenNoGoModExists(t *testing.T) {
	original := callerLookup
	t.Cleanup(func() { callerLookup = original })
	dir := t.TempDir()
	callerLookup = func(int) (uintptr, string, int, bool) {
		return 0, filepath.Join(dir, "caller.go"), 0, true
	}

	if _, err := ParallelGuardModuleRoot(); err == nil {
		t.Fatal("ParallelGuardModuleRoot returned no error when no go.mod exists above the caller")
	}
}

// TestParallelGuardModuleRootFindsRealModuleRoot pins the success path: this
// repository's own go.mod, found by walking up from this very file.
func TestParallelGuardModuleRootFindsRealModuleRoot(t *testing.T) {
	t.Parallel()
	root, err := ParallelGuardModuleRoot()
	if err != nil {
		t.Fatalf("ParallelGuardModuleRoot: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "go.mod")); err != nil {
		t.Fatalf("resolved root %q has no go.mod: %v", root, err)
	}
}

