// funcTypeFromSource parses a single top-level function declaration and
// returns its *ast.FuncType, for exercising singleTestingTParam directly
// against synthetic signatures without writing any file to disk.
func funcTypeFromSource(t *testing.T, source string) *ast.FuncType {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "synthetic.go", "package p\n"+source, 0)
	if err != nil {
		t.Fatalf("parse fixture: %v", err)
	}
	fd, ok := file.Decls[0].(*ast.FuncDecl)
	if !ok {
		t.Fatalf("fixture's first declaration is not a function: %#v", file.Decls[0])
	}
	return fd.Type
}

func TestSingleTestingTParamRejectsAnyShapeOtherThanExactlyOnePointerToTestingT(t *testing.T) {
	t.Parallel()
	cases := map[string]string{
		"no parameters":                       "func NoParams() {}\n",
		"two parameters":                      "func TwoParams(t *testing.T, u *testing.T) {}\n",
		"a value, not a pointer":              "func ValueParam(t testing.T) {}\n",
		"a pointer to another type":           "func WrongPointer(t *int) {}\n",
		"a pointer to another package's type": "func WrongPackage(t *other.T) {}\n",
	}
	for name, source := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			if singleTestingTParam(funcTypeFromSource(t, source)) {
				t.Fatalf("singleTestingTParam accepted a %s signature", name)
			}
		})
	}
}

func TestSingleTestingTParamAcceptsExactlyOnePointerToTestingT(t *testing.T) {
	t.Parallel()
	fn := funcTypeFromSource(t, "func TestOK(t *testing.T) {}\n")
	if !singleTestingTParam(fn) {
		t.Fatal("singleTestingTParam rejected a plain func(t *testing.T) signature")
	}
}

// commentedPositionFromSource parses source containing exactly one
// `// marker` line followed immediately by `func Marked() {}`, returning the
// parsed file, its FileSet, and the position of the `func` declaration --
// enough to exercise nolintParalleltestReason exactly the way scanFile does.
func commentedPositionFromSource(t *testing.T, source string) (*token.FileSet, *ast.File, token.Pos) {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "synthetic.go", source, parser.ParseComments)
	if err != nil {
		t.Fatalf("parse fixture: %v", err)
	}
	fd, ok := file.Decls[len(file.Decls)-1].(*ast.FuncDecl)
	if !ok {
		t.Fatalf("fixture's last declaration is not a function: %#v", file.Decls[len(file.Decls)-1])
	}
	return fset, file, fd.Pos()
}

func TestNolintParalleltestReasonFindsNoComment(t *testing.T) {
	t.Parallel()
	fset, file, pos := commentedPositionFromSource(t, "package p\n\nfunc Marked() {}\n")
	reason, bare := nolintParalleltestReason(fset, file, pos)
	if reason != "" || bare {
		t.Fatalf("nolintParalleltestReason = (%q, %v), want (\"\", false) with no comment present", reason, bare)
	}
}

func TestNolintParalleltestReasonReportsBareDirectiveAsMissingAReason(t *testing.T) {
	t.Parallel()
	fset, file, pos := commentedPositionFromSource(t, "package p\n\n//nolint:paralleltest\nfunc Marked() {}\n")
	reason, bare := nolintParalleltestReason(fset, file, pos)
	if reason != "" || !bare {
		t.Fatalf("nolintParalleltestReason = (%q, %v), want (\"\", true) for a bare directive", reason, bare)
	}
}

func TestNolintParalleltestReasonReturnsTheStatedReason(t *testing.T) {
	t.Parallel()
	fset, file, pos := commentedPositionFromSource(t, "package p\n\n//nolint:paralleltest // a real reason\nfunc Marked() {}\n")
	reason, bare := nolintParalleltestReason(fset, file, pos)
	if bare || reason != "a real reason" {
		t.Fatalf("nolintParalleltestReason = (%q, %v), want (\"a real reason\", false)", reason, bare)
	}
}

// writeScanFixture writes one _test.go file under root/dir so ScanSerialTests
// (the real filepath.Walk-driven entry point) parses it, exercising the
// walk callback's own branches rather than scanFile in isolation.
func writeScanFixture(t *testing.T, root, dir, filename, content string) {
	t.Helper()
	full := filepath.Join(root, dir)
	if err := os.MkdirAll(full, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(full, filename), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

